#!/bin/bash
# test-no-source.sh — o `conf` e o `tl` do PACOTE nunca são `source`ados no servidor (26/10/2026).
# O kattis/sidecar.sh roda a cada create/edit/upload de problema (cdmoj handlers/problems/*), o export roda
# no "⬇ ICPC" e o gen-problem-json.sh a cada indexação — todos NA API. Os dois primeiros faziam `source` do
# conf e do tl do AUTOR (kt_collect) e o terceiro do tl do pacote (fallback sem TL calibrado): uma linha
# `X=$(…)` executava código no servidor. Prende:
#   · kt_collect, sidecar.sh e export.sh com conf e tl ENVENENADOS: nenhuma marca nasce e os valores certos
#     saem (calibrafactor, ULIMITS, TL só numérico, a última linha vencendo);
#   · o fallback do gen-problem-json.sh idem;
#   · inventário: nenhum script do servidor faz `source` de arquivo do pacote.
# Sem jaula e sem rede. A parte do kattis/ precisa de python3+pyyaml (pula sem eles). `make test-no-source`.
set -u
MT="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
pass=0; fail=0
ck(){ if eval "$2"; then echo "  ok: $1"; ((pass++)); else echo "  FAIL: $1 :: ${DBG:-}"; ((fail++)); fi; }
M="$W/marca"   # nenhum arquivo $M.* pode existir no fim
marks(){ find "$W" -maxdepth 1 -name 'marca.*' | wc -l; }

P="$W/repo/pp"; mkdir -p "$P/docs" "$P/tests/input" "$P/tests/output" "$P/sols/good"
printf 'Some.\n\n## Entrada\n\nx\n\n## Saída\n\ny\n' > "$P/docs/enunciado.md"
echo 1 > "$P/tests/input/sample1"; echo 1 > "$P/tests/output/sample1"; echo autor > "$P/author"
printf 'int main(){return 0;}\n' > "$P/sols/good/a.c"
cat > "$P/conf" <<EOF
TLMOD[calibrafactor]="1.5"
ULIMITS[-v]=1048576  # comentário
ULIMITS[-f]=\$(touch $M.conf1)
X=\$(touch $M.conf2)
Y=\`touch $M.conf3\`
ALLOWPARALLELTEST=y
EOF
cat > "$P/tl" <<EOF
#Generated by calibreitor on juiz (data)
TL[c]=.5
TL[cpp]=\$(touch $M.tl1)
TL[py]=1.25
TL[py]=2
\$(touch $M.tl2)
EOF

echo "== kattis/: kt_collect, sidecar e export =="
if command -v python3 >/dev/null && python3 -c 'import yaml' 2>/dev/null; then
  ( source "$MT/kattis/lib.sh"; kt_collect "$P" "repo#pp" ) > "$W/collect.json" 2>"$W/collect.err"
  DBG="$(head -c 300 "$W/collect.err") marcas=$(marks)"
  ck "kt_collect não executa nada do conf/tl" '[[ "$(marks)" == 0 ]]'
  DBG="$(jq -c '{calibrafactor, ulimits, tl, allowparallel}' "$W/collect.json" 2>&1)"
  ck "calibrafactor sem as aspas" '[[ "$(jq -r .calibrafactor "$W/collect.json")" == 1.5 ]]'
  ck "ULIMITS: valor sem o comentário; o \$(…) vira texto, nunca roda" \
     '[[ "$(jq -r ".ulimits[\"-v\"]" "$W/collect.json")" == 1048576 && "$(jq -r ".ulimits[\"-f\"]" "$W/collect.json")" == "\$(touch" ]]'
  ck "TL só numérico, a última linha vence: {c:0.5, py:2}" '[[ "$(jq -c .tl "$W/collect.json")" == "{\"c\":0.5,\"py\":2}" ]]'
  ck "escalar do conf (ALLOWPARALLELTEST)" '[[ "$(jq -r .allowparallel "$W/collect.json")" == y ]]'
  bash "$MT/kattis/sidecar.sh" "$P" "repo#pp" >/dev/null 2>&1
  DBG="marcas=$(marks) $(ls "$P")"
  ck "sidecar.sh (o do create/edit/upload): sem marca, problem.yaml gerado" '[[ "$(marks)" == 0 && -s "$P/problem.yaml" ]]'
  ck "sidecar: .kattis.json com os TLs certos" '[[ "$(jq -c .per_language_tl "$P/.kattis.json")" == "{\"c\":0.5,\"py\":2}" ]]'
  bash "$MT/kattis/export.sh" "$P" "repo#pp" "$W/out" >/dev/null 2>&1
  DBG="marcas=$(marks)"
  ck "export.sh: sem marca, pacote gerado" '[[ "$(marks)" == 0 && -s "$W/out/problem.yaml" ]]'
else
  echo "  (python3+pyyaml ausentes — parte do kattis/ pulada)"
fi

echo "== gen-problem-json: fallback do tl do pacote =="
export CONTESTSDIR="$W/c" RUNDIR="$W/run" MOJ_TL_STORE="$W/run/tl"; mkdir -p "$CONTESTSDIR/treino/var/jsons" "$MOJ_TL_STORE"
rm -f "$P/problem.yaml" "$P/.kattis.json"
bash "$MT/gen-problem-json.sh" "$P" >/dev/null 2>"$W/gpj.err"
J="$CONTESTSDIR/treino/var/jsons-private/repo#pp.json"
DBG="marcas=$(marks) $(head -c 300 "$W/gpj.err")"
ck "gen-problem-json não executa nada do tl" '[[ "$(marks)" == 0 ]]'
DBG="$(jq -c .time_limits "$J" 2>&1)"
ck "time_limits do fallback: {c:.5, py:2} (string, como antes)" '[[ "$DBG" == "{\"c\":\".5\",\"py\":\"2\"}" ]]'

echo "== inventário: nenhum script do servidor faz source de arquivo do pacote =="
BAD="$(grep -nE '(^|[;&|({[:space:]])(source|\.)[[:space:]]+"?\$\{?(pkg|PKG|TLFILE|P)\b' \
        "$MT"/kattis/*.sh "$MT/gen-problem-json.sh" "$MT/gen-problem-owners.sh" "$MT/statement-langs.sh" \
        "$MT/render-statement.sh" "$MT/tl-checksum.sh" 2>/dev/null)"
DBG="$BAD"
ck "kattis/*, gen-problem-json, gen-problem-owners, statement-langs, render-statement, tl-checksum" '[[ -z "$BAD" ]]'

echo "no-source: $pass ok, $fail falhas"; [[ $fail -eq 0 ]]
