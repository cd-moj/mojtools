#!/bin/bash
# test-calib-lanes.sh — a calibração em RAIAS (26/10/2026; pedido do Ribas: rodar as soluções do mesmo tipo em
# paralelo p/ reduzir a espera). Roda o calibreitor.sh + build-and-test.sh REAIS numa cópia do mojtools com um
# cage-run.sh FALSO (o de test-calib-methods.sh, que também registra a afinidade de CPU de cada execução e, com
# FAKE_SLEEP, demora). Prende:
#   · serial (sem MOJ_CPU_GROUPS) × 3 raias ("0|1|2"): a MESMA tabela (fora a linha da data), o MESMO
#     .calib-sols.json e o MESMO log (fora o caminho do workdir) — o pai lê os resultados EM ORDEM;
#   · cada solução numa raia pinada no seu grupo; as raias se sobrepõem no tempo (parede bem menor que a serial);
#   · a good que falha sai no log na ordem, com a frase-contrato "was waiting Accepted";
#   · CALIBRATE_ONLY_GOOD pula a fase 2; mais raias que soluções não trava; MOJ_CALIB_LANES=0 = uma raia;
#   · o MOJ_RELEASE_FILE do agente segue vazio.
# Sem jaula, sem rede. `make test-calib-lanes`.
set -u
MT="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
W="${KEEPW:-$(mktemp -d)}"; [[ -n "${KEEPW:-}" ]] || trap 'rm -rf "$W"' EXIT
pass=0; fail=0
ck(){ if eval "$2"; then echo "  ok: $1"; ((pass++)); else echo "  FAIL: $1 :: ${DBG:0:600}"; ((fail++)); fi; DBG=""; }

H="$W/mt"; mkdir -p "$H"
cp "$MT"/{calibreitor.sh,build-and-test.sh,tl-methods.sh,lang-canon.sh,gen-report.sh,score-summary.sh,tl-checksum.sh} "$H"/
cp -r "$MT/lang" "$H/lang"
cat > "$H/cage-run.sh" <<'EOF'
#!/bin/bash
# cage-run FALSO: compilação = BIN=sol; execução = o tempo da linha TIMES da fonte, morto no teto -T; registra a
# afinidade de CPU (a raia) e, com FAKE_SLEEP, demora de verdade (p/ medir a sobreposição das raias)
IN=""; OUT=""; TLOG=""; RW=""; SERR=""; BW=""; D=""; T=""
while (( $# )); do case "$1" in
  -i) IN="$2"; shift 2;; -o) OUT="$2"; shift 2;; -t) TLOG="$2"; shift 2;; -w) RW="$2"; shift 2;;
  -s) SERR="$2"; shift 2;; -B) BW="$2"; shift 2;; -d) D="$2"; shift 2;; -T) T="$2"; shift 2;;
  -r|-R|-M|-b|-S|-U|-C) shift 2;; *) shift;; esac; done
[[ -n "$BW" ]] && : > "$BW"; [[ -n "$SERR" ]] && : > "$SERR"
if [[ -n "$RW" && -z "$IN" ]]; then echo "BIN=sol" > "$OUT"; : > "$TLOG"; exit 0; fi
name="$(basename "$IN")"
spec="$(grep -h -m1 -o 'TIMES .*' "$D"/* 2>/dev/null | head -1)"; wrong="$(grep -h -m1 -o 'WRONG .*' "$D"/* 2>/dev/null | head -1)"
read -r _ real rest <<<"$spec"; real="${real:-0.05}"
for kv in $rest; do [[ "${kv%%=*}" == "$name" ]] && real="${kv#*=}"; done
src="$(grep -l -m1 'TIMES' "$D"/* 2>/dev/null | head -1)"
[[ -n "${FAKE_SLEEP:-}" ]] && sleep "$FAKE_SLEEP"
echo "run $(basename "${src:-?}") $name aff=$(taskset -pc $$ 2>/dev/null | sed 's/.*: //')" >> "$FAKE_LOG"
rc=0
if [[ "$(echo "$real > $T" | bc -l)" == 1 ]]; then real="$T"; rc=137; : > "$OUT"
elif [[ " ${wrong#WRONG } " == *" $name "* ]]; then echo errado > "$OUT"
else cat "$IN" > "$OUT"; fi
printf 'real %s\nuser 0\nsys 0\nres 100\ncpu 99%%\n' "$real" > "$TLOG"
exit $rc
EOF
chmod +x "$H/cage-run.sh"
export FAKE_LOG="$W/cage.log" HOSTNAME=juizteste TMPDIR="$W/tmp"; mkdir -p "$TMPDIR"
unset MOJ_TL_METHOD MOJ_CALIBRATING MOJ_CALIB_ALT MOJ_TLFILE MOJ_PROBLEM_ID CAGE_ROOT MOJ_PARALLEL MOJ_CPU_GROUPS \
      MOJ_CALIB_LANES CALIBRATE_ONLY_GOOD MOJ_TEST_CPUS

# pacote: 3 testes; três good (a C passa; a py é a mais lenta; a cpp ERRA o t2 = a good que falha), pass, 2 slow, wrong
P="$W/repo/pp"; mkdir -p "$P/tests/input" "$P/tests/output" "$P"/sols/{good,slow,pass,wrong}
for t in sample1 t2 big3; do echo "$t" > "$P/tests/input/$t"; cp "$P/tests/input/$t" "$P/tests/output/$t"; done
printf 'ULIMITS[-u]=%s\n' "$(ulimit -Hu)" > "$P/conf"
printf '// TIMES 0.10 big3=0.21\nint main(){}\n' > "$P/sols/good/a.c"
printf '# TIMES 0.50 big3=1.30\n' > "$P/sols/good/b.py"
printf '// TIMES 0.10\n// WRONG t2\nint main(){}\n' > "$P/sols/good/c.cpp"
printf '// TIMES 0.30\n' > "$P/sols/pass/p.c"
printf '// TIMES 0.10 big3=9\n' > "$P/sols/slow/s.c"
printf '// TIMES 0.10 t2=9\n' > "$P/sols/slow/s2.c"
printf '// TIMES 0.10\n// WRONG big3\n' > "$P/sols/wrong/w.c"

# calib <rótulo> [VAR=valor…] : roda o calibreitor e guarda log, tabela, vetor e o log do cage-run do rótulo
calib(){
  local tag="$1"; shift
  rm -f "$P"/tl "$P"/tl.* "$P/.calib-sols.json"; : > "$FAKE_LOG"
  local t0=$EPOCHREALTIME
  env "$@" bash "$H/calibreitor.sh" "$P" > "$W/$tag.log" 2>&1
  echo "$t0 $EPOCHREALTIME" | awk '{printf "%.2f", $2 - $1}' > "$W/$tag.wall"
  cp "$P/tl.juizteste" "$W/$tag.tl" 2>/dev/null; cp "$P/.calib-sols.json" "$W/$tag.sols" 2>/dev/null; cp "$FAKE_LOG" "$W/$tag.cage"
}
norm_log(){ sed -E -e 's/^#Generated by calibreitor on .*/#Generated/' -e "s#Check [^ ]*#Check WORKDIR#" "$1"; }
norm_tl(){ grep -v '^#Generated' "$1"; }

echo "== serial × 3 raias: a mesma tabela, o mesmo vetor e o mesmo log =="
calib serial
calib raias MOJ_CPU_GROUPS="0|1|2"
DBG="$(diff <(norm_tl "$W/serial.tl") <(norm_tl "$W/raias.tl"))"
ck "tabela (TL e TLKATTIS) idêntica"                       '[[ -s "$W/serial.tl" && -z "$DBG" ]]'
DBG="$(diff <(jq -S . "$W/serial.sols") <(jq -S . "$W/raias.sols"))"
ck ".calib-sols.json idêntico (7 soluções, na ordem das categorias)" '[[ -z "$DBG" && "$(jq length "$W/raias.sols")" == 7 && "$(jq -r "map(.category) | join(\",\")" "$W/raias.sols")" == "good,good,good,pass,slow,slow,wrong" ]]'
DBG="$(diff <(norm_log "$W/serial.log") <(norm_log "$W/raias.log"))"
ck "log idêntico (fora o caminho do workdir)"              '[[ -s "$W/serial.log" && -z "$DBG" ]]'
DBG="$(cat "$W/raias.log")"
ck "a good que falha, na ordem, com a frase-contrato"      'grep -q "c.cpp got .*was waiting Accepted" "$W/raias.log" && [[ "$(grep -n "^c.cpp:" "$W/raias.log" | cut -d: -f1)" -gt "$(grep -n "^b.py:" "$W/raias.log" | cut -d: -f1)" ]]'
ck "W da linguagem pelo pai: TL[py] = 1,35 × 1,30 + 0,02" 'grep -qE "^TL\[py\]=1\.7750" "$W/raias.tl"'
# (a ordem dentro da categoria é a do glob, que segue o locale: s2.c antes de s.c em pt_BR — vale a do serial)
ck "fase 2 com os cabeçalhos, na ordem do serial"          '[[ "$(grep -E "^(PASS|SLOW|WRONG) solutions:|^[a-z0-9]+\.[a-z]+:" "$W/raias.log" | tr "\n" " ")" == "$(grep -E "^(PASS|SLOW|WRONG) solutions:|^[a-z0-9]+\.[a-z]+:" "$W/serial.log" | tr "\n" " ")" && "$(grep -cE "^(PASS|SLOW|WRONG) solutions:" "$W/raias.log")" == 3 ]]'

if taskset -pc 0,1,2 $$ >/dev/null 2>&1 && (( $(nproc) >= 3 )); then
  echo "== as raias: pinadas cada uma no seu grupo, e de fato em paralelo =="
  DBG="$(cat "$W/raias.cage")"
  ck "cada execução numa CPU só, das três dos grupos"       '! grep -qvE "aff=[012]$" "$W/raias.cage"'
  ck "as três raias foram usadas"                          '[[ "$(grep -oE "aff=[012]$" "$W/raias.cage" | sort -u | wc -l)" == 3 ]]'
  ck "a solução fica na raia que a pegou (os 3 testes no mesmo grupo)" '[[ "$(awk "{print \$2, \$4}" "$W/raias.cage" | sort -u | awk "{print \$1}" | sort | uniq -d | wc -l)" == 0 ]]'
  DBG="$(cat "$W/serial.cage" | head -3)"
  ck "serial: sem pin (a afinidade do processo)"           '! grep -qE "aff=[012]$" "$W/serial.cage" || [[ "$(nproc)" -le 1 ]]'
  calib lento-serial FAKE_SLEEP=0.3 CALIBRATE_ONLY_GOOD=1
  calib lento-raias FAKE_SLEEP=0.3 CALIBRATE_ONLY_GOOD=1 MOJ_CPU_GROUPS="0|1|2"
  ws="$(cat "$W/lento-serial.wall")"; wr="$(cat "$W/lento-raias.wall")"; DBG="serial=${ws}s raias=${wr}s"
  ck "3 raias: parede bem menor que a serial (< 60 %) [serial ${ws}s, raias ${wr}s]" '[[ "$(echo "$wr < 0.6 * $ws" | bc -l)" == 1 ]]'
  calib zero MOJ_CPU_GROUPS="0|1|2" MOJ_CALIB_LANES=0
  DBG="$(head -3 "$W/zero.cage")"
  ck "MOJ_CALIB_LANES=0: uma raia (sem pin por raia), mesmo resultado" '! grep -qE "aff=[12]$" "$W/zero.cage" && [[ -z "$(diff <(norm_tl "$W/serial.tl") <(norm_tl "$W/zero.tl"))" ]]'
else
  echo "  (menos de 3 CPUs: pulei a afinidade e a sobreposição)"
fi

echo "== bordas: só as good; mais raias que soluções; o arquivo de liberação do agente =="
calib so-good MOJ_CPU_GROUPS="0|1|2" CALIBRATE_ONLY_GOOD=1
DBG="$(cat "$W/so-good.cage")"
ck "CALIBRATE_ONLY_GOOD: a fase 2 não roda"                '! grep -qE "^run (p|s|s2|w)\.c " "$W/so-good.cage" && grep -q "pulando verificação verbose" "$W/so-good.log"'
: > "$W/released"
calib muitas MOJ_CPU_GROUPS="0|0|0|0|0|0|0|0|0" MOJ_RELEASE_FILE="$W/released"
ck "9 raias p/ 3 e 4 soluções: termina, com o resultado do serial" '[[ -z "$(diff <(norm_tl "$W/serial.tl") <(norm_tl "$W/muitas.tl"))" && "$(jq length "$W/muitas.sols")" == 7 ]]'
ck "o MOJ_RELEASE_FILE segue vazio (a calibração nunca libera grupo)" '[[ ! -s "$W/released" ]]'
ck "nenhum resto de raia no TMPDIR (claim e saídas por item)" '[[ -z "$(find "$TMPDIR" -maxdepth 1 \( -name "tmp.*.claim" -o -name "tmp.*.item.*" \) 2>/dev/null)" ]]'

echo; echo "RESULT: $pass passed, $fail failed"
(( fail == 0 ))
