#!/bin/bash
# test-calib-memo.sh — CALIBRAÇÃO INCREMENTAL (10/11/2026; opt-in): o calibreitor grava o retrato de cada solução em
# MOJ_CALIB_MEMO_DIR e, só com MOJ_CALIB_REUSE=1, reaproveita o da MESMA chave em vez de rodar. Prende:
#   · sem o diretório nada muda; com ele e sem o reuse, tudo roda e o memo nasce;
#   · com o reuse e nada mudado: nada roda, e a tabela, o vetor (menos o reused_at) e o log são os mesmos;
#   · solução NOVA: só ela roda; good mudada (W novo ⇒ tabela nova): ela e TODA a fase 2 rodam;
#   · conf ou teste mudado: tudo roda; memo vencido (TTL): roda; o resumo diz quantas vieram do memo.
# Mesmo harness do test-calib-lanes.sh (calibreitor + build-and-test REAIS, cage-run FALSO). `make test-calib-memo`.
set -u
MT="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
W="${KEEPW:-$(mktemp -d)}"; [[ -n "${KEEPW:-}" ]] || trap 'rm -rf "$W"' EXIT
pass=0; fail=0
ck(){ if eval "$2"; then echo "  ok: $1"; ((pass++)); else echo "  FAIL: $1 :: ${DBG:0:600}"; ((fail++)); fi; DBG=""; }

H="$W/mt"; mkdir -p "$H"
cp "$MT"/{calibreitor.sh,build-and-test.sh,tl-methods.sh,lang-canon.sh,gen-report.sh,score-summary.sh,tl-checksum.sh} "$H"/
cp -r "$MT/lang" "$H/lang"
cat > "$H/cage-run.sh" <<'EOF'
#!/bin/bash
# cage-run FALSO: compilação = BIN=sol; execução = o tempo da linha TIMES da fonte, morto no teto -T; registra a
# afinidade de CPU (a raia) e, com FAKE_SLEEP, demora de verdade (p/ medir a sobreposição das raias)
IN=""; OUT=""; TLOG=""; RW=""; SERR=""; BW=""; D=""; T=""
while (( $# )); do case "$1" in
  -i) IN="$2"; shift 2;; -o) OUT="$2"; shift 2;; -t) TLOG="$2"; shift 2;; -w) RW="$2"; shift 2;;
  -s) SERR="$2"; shift 2;; -B) BW="$2"; shift 2;; -d) D="$2"; shift 2;; -T) T="$2"; shift 2;;
  -r|-R|-M|-b|-S|-U|-C) shift 2;; *) shift;; esac; done
[[ -n "$BW" ]] && : > "$BW"; [[ -n "$SERR" ]] && : > "$SERR"
if [[ -n "$RW" && -z "$IN" ]]; then echo "BIN=sol" > "$OUT"; : > "$TLOG"; exit 0; fi
name="$(basename "$IN")"
spec="$(grep -h -m1 -o 'TIMES .*' "$D"/* 2>/dev/null | head -1)"; wrong="$(grep -h -m1 -o 'WRONG .*' "$D"/* 2>/dev/null | head -1)"
read -r _ real rest <<<"$spec"; real="${real:-0.05}"
for kv in $rest; do [[ "${kv%%=*}" == "$name" ]] && real="${kv#*=}"; done
src="$(grep -l -m1 'TIMES' "$D"/* 2>/dev/null | head -1)"
[[ -n "${FAKE_SLEEP:-}" ]] && sleep "$FAKE_SLEEP"
echo "run $(basename "${src:-?}") $name aff=$(taskset -pc $$ 2>/dev/null | sed 's/.*: //')" >> "$FAKE_LOG"
rc=0
if [[ "$(echo "$real > $T" | bc -l)" == 1 ]]; then real="$T"; rc=137; : > "$OUT"
elif [[ " ${wrong#WRONG } " == *" $name "* ]]; then echo errado > "$OUT"
else cat "$IN" > "$OUT"; fi
printf 'real %s\nuser 0\nsys 0\nres 100\ncpu 99%%\n' "$real" > "$TLOG"
exit $rc
EOF
chmod +x "$H/cage-run.sh"
export FAKE_LOG="$W/cage.log" HOSTNAME=juizteste TMPDIR="$W/tmp"; mkdir -p "$TMPDIR"
unset MOJ_TL_METHOD MOJ_CALIBRATING MOJ_CALIB_ALT MOJ_TLFILE MOJ_PROBLEM_ID CAGE_ROOT MOJ_PARALLEL MOJ_CPU_GROUPS \
      MOJ_CALIB_LANES CALIBRATE_ONLY_GOOD MOJ_TEST_CPUS

# pacote: 3 testes; três good (a C passa; a py é a mais lenta; a cpp ERRA o t2 = a good que falha), pass, 2 slow, wrong
P="$W/repo/pp"; mkdir -p "$P/tests/input" "$P/tests/output" "$P"/sols/{good,slow,pass,wrong}
for t in sample1 t2 big3; do echo "$t" > "$P/tests/input/$t"; cp "$P/tests/input/$t" "$P/tests/output/$t"; done
printf 'ULIMITS[-u]=%s\n' "$(ulimit -Hu)" > "$P/conf"
printf '// TIMES 0.10 big3=0.21\nint main(){}\n' > "$P/sols/good/a.c"
printf '# TIMES 0.50 big3=1.30\n' > "$P/sols/good/b.py"
printf '// TIMES 0.10\n// WRONG t2\nint main(){}\n' > "$P/sols/good/c.cpp"
printf '// TIMES 0.30\n' > "$P/sols/pass/p.c"
printf '// TIMES 0.10 big3=9\n' > "$P/sols/slow/s.c"
printf '// TIMES 0.10 t2=9\n' > "$P/sols/slow/s2.c"
printf '// TIMES 0.10\n// WRONG big3\n' > "$P/sols/wrong/w.c"

# calib <rótulo> [VAR=valor…] : roda o calibreitor e guarda log, tabela, vetor e o log do cage-run do rótulo
calib(){
  local tag="$1"; shift
  rm -f "$P"/tl "$P"/tl.* "$P/.calib-sols.json"; : > "$FAKE_LOG"
  local t0=$EPOCHREALTIME
  env "$@" bash "$H/calibreitor.sh" "$P" > "$W/$tag.log" 2>&1; echo "$?" > "$W/$tag.rc"
  echo "$t0 $EPOCHREALTIME" | awk '{printf "%.2f", $2 - $1}' > "$W/$tag.wall"
  cp "$P/tl.juizteste" "$W/$tag.tl" 2>/dev/null; cp "$P/.calib-sols.json" "$W/$tag.sols" 2>/dev/null; cp "$FAKE_LOG" "$W/$tag.cage"
}
# a linha "[raia N] solução" é o início de cada solução (a ordem entre raias é do relógio): fora da comparação
norm_log(){ sed -E -e 's/^#Generated by calibreitor on .*/#Generated/' -e "s#Check [^ ]*#Check WORKDIR#" -e '/^  \[raia [0-9]+\] /d' "$1"; }
norm_tl(){ grep -v '^#Generated' "$1"; }
M="$W/memo"
ran(){ awk '{print $2}' "$W/$1.cage" | LC_ALL=C sort -u | tr '\n' ' '; }
nsols(){ jq '[.[] | select(.reused_at)] | length' "$W/$1.sols"; }
norm_memo(){ norm_log "$1" | sed -e '/^Calibração incremental/d' -e '/^$/d'; }

echo "== sem o diretório do memo: nada muda =="
calib base
ck "calibrou e nenhum memo nasceu"                         '[[ "$(cat "$W/base.rc")" == 0 && ! -e "$M" ]]'

echo "== com o diretório, sem o reuse: tudo roda e o memo nasce =="
calib grava MOJ_CALIB_MEMO_DIR="$M"
DBG="$(ls "$M" 2>&1)"
ck "7 retratos (um por solução)"                            '[[ "$(find "$M" -mindepth 1 -maxdepth 1 -type d ! -name ".*" | wc -l)" == 7 ]]'
ck "todas as soluções rodaram"                             '[[ "$(ran grava)" == "a.c b.py c.cpp p.c s.c s2.c w.c " ]]'
ck "o vetor não tem reused_at"                             '[[ "$(nsols grava)" == 0 ]]'
DBG="$(diff <(norm_tl "$W/base.tl") <(norm_tl "$W/grava.tl"))"
ck "mesma tabela que sem o memo"                           '[[ -z "$DBG" ]]'

echo "== reuse sem mudança: nada roda, mesmo resultado =="
calib reusa MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
DBG="$(cat "$W/reusa.cage")"
ck "nenhuma execução"                                      '[[ ! -s "$W/reusa.cage" ]]'
DBG="$(diff <(norm_tl "$W/grava.tl") <(norm_tl "$W/reusa.tl"))"
ck "a mesma tabela"                                        '[[ -s "$W/reusa.tl" && -z "$DBG" ]]'
DBG="$(diff <(jq -S "map(del(.reused_at))" "$W/grava.sols") <(jq -S "map(del(.reused_at))" "$W/reusa.sols"))"
ck "o mesmo vetor, com reused_at nas 7"                    '[[ -z "$DBG" && "$(nsols reusa)" == 7 ]]'
DBG="$(diff <(norm_memo "$W/grava.log") <(norm_memo "$W/reusa.log"))"
ck "o mesmo log (fora as linhas de raia e o resumo)"       '[[ -z "$DBG" ]]'
ck "o log diz o que foi reaproveitado e o resumo conta"    '[[ "$(grep -c "— reaproveitado (medido em" "$W/reusa.log")" == 7 ]] && grep -q "7 solução(ões) reaproveitada(s)" "$W/reusa.log"'

echo "== solução NOVA: só ela roda =="
printf '// TIMES 0.20\n' > "$P/sols/pass/p2.c"
calib nova MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
ck "só a p2.c rodou"                                       '[[ "$(ran nova)" == "p2.c " ]]'
ck "8 no vetor, 7 reaproveitadas"                          '[[ "$(jq length "$W/nova.sols")" == 8 && "$(nsols nova)" == 7 ]]'

echo "== good MUDADA (W novo, tabela nova): ela e toda a fase 2 rodam; as outras good não =="
printf '# TIMES 0.50 big3=1.50\n' > "$P/sols/good/b.py"
calib good MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
DBG="$(ran good)"
ck "b.py + p.c p2.c s.c s2.c w.c rodaram; a.c e c.cpp não" '[[ "$(ran good)" == "b.py p.c p2.c s.c s2.c w.c " ]]'
ck "o TL do py seguiu o W novo (1,35 × 1,50 + 0,02)"       'grep -qE "^TL\[py\]=2\.045" "$W/good.tl"'

echo "== conf ou teste mudado: tudo roda =="
calib estavel MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
ck "(de novo sem mudança: nada roda)"                      '[[ ! -s "$W/estavel.cage" ]]'
printf 'STOPWHEN_WA=n\n' >> "$P/conf"
calib conf MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
ck "conf mudado: as 8 rodaram"                             '[[ "$(ran conf | wc -w)" == 8 ]]'
echo "t2b" > "$P/tests/output/t2"
calib teste MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
ck "saída esperada mudada: as 8 rodaram"                   '[[ "$(ran teste | wc -w)" == 8 ]]'
echo "t2" > "$P/tests/output/t2"

echo "== memo vencido e reuse sem diretório =="
calib re1 MOJ_CALIB_MEMO_DIR="$M"
for d in "$M"/*/; do printf '%s\n' "$((EPOCHSECONDS - 20*86400))" > "$d/.memo-at"; done
calib vencido MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1
ck "retrato com mais de 14 dias não vale: as 8 rodaram"    '[[ "$(ran vencido | wc -w)" == 8 && "$(nsols vencido)" == 0 ]]'
calib semdir MOJ_CALIB_REUSE=1
ck "MOJ_CALIB_REUSE sem o diretório: roda tudo"            '[[ "$(ran semdir | wc -w)" == 8 ]] && ! grep -q "Calibração incremental" "$W/semdir.log"'

echo "== com raias (3 grupos): o reuse vale em cada raia =="
calib raias0 MOJ_CALIB_MEMO_DIR="$M"
calib raias MOJ_CALIB_MEMO_DIR="$M" MOJ_CALIB_REUSE=1 MOJ_CPU_GROUPS="0|1|2"
DBG="$(diff <(norm_tl "$W/raias0.tl") <(norm_tl "$W/raias.tl"))"
ck "nada rodou e a tabela é a mesma"                       '[[ ! -s "$W/raias.cage" && -s "$W/raias.tl" && -z "$DBG" && "$(nsols raias)" == 8 ]]'

echo; echo "RESULT: $pass passed, $fail failed"
(( fail == 0 ))
